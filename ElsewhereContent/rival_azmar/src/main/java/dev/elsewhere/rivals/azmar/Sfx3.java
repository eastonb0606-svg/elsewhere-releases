package dev.elsewhere.rivals.azmar;

import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.WeakHashMap;
import net.minecraft.core.Registry;
import net.minecraft.core.particles.ParticleTypes;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.resources.Identifier;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.sounds.SoundEvent;
import net.minecraft.sounds.SoundSource;
import net.minecraft.world.entity.Entity;
import net.minecraft.world.entity.LivingEntity;

/**
 * sfx lane (3.0, generated by ElsewhereContent/audio/sfx/wire_sfx3.py): this module's own boss sound identity, so no
 * boss here uses a vanilla ender dragon or wither sound. Events are {@code elsewhere:sfx3.<boss>.<cue>} in sounds.json:
 * signature files are original procedural synthesis (audio/sfx/synth_sfx.py), the rest are re-pitched vanilla events.
 * Kill switch: {@code "sfx3_rival_azmar": false} in {@code config/elsewhere-overhaul3.json} (the shared 3.0 switch file) or
 * {@code -Delsewhere.overhaul3.sfx3_rival_azmar=false} brings back the 2.x sounds. The events stay registered either way, so client
 * and server registries always match.
 * Everything here runs on an event (phase change, attack start, death); a per-entity gate drops repeats, so a caller that
 * fires every tick still makes at most one sound per gap.
 */
public final class Sfx3 {
	private Sfx3() {}

	public static final String CONFIG_KEY = "sfx3_rival_azmar";
	/** boss id -> its cues (each one is the event sfx3.<boss>.<cue>). */
	public static final Map<String, List<String>> CUES = new LinkedHashMap<>();
	private static final Map<String, SoundEvent> EVENTS = new LinkedHashMap<>();
	private static final Map<Entity, long[]> LAST = new WeakHashMap<>();
	private static Boolean enabled;
	/** Banner names (text before any ':') that are real attacks: only these get a wind-up; opening/state banners stay silent. */
	public static final java.util.Set<String> ATTACK_NAMES = java.util.Set.of();

	static {
		CUES.put("azmar", List.of("sistrum", "brass", "firesand"));
	}

	public static boolean isAttack(String banner) {
		return banner != null && ATTACK_NAMES.contains(banner.split(":", 2)[0].trim());
	}

	/** Registers every sfx3 event (call once from the module's init, before registries freeze). */
	public static void init() {
		if (!EVENTS.isEmpty()) return;
		for (var e : CUES.entrySet()) for (String c : e.getValue()) {
			Identifier id = Identifier.fromNamespaceAndPath("elsewhere", "sfx3." + e.getKey() + "." + c);
			SoundEvent ev = BuiltInRegistries.SOUND_EVENT.containsKey(id) ? BuiltInRegistries.SOUND_EVENT.getValue(id)
				: Registry.register(BuiltInRegistries.SOUND_EVENT, id, SoundEvent.createVariableRangeEvent(id));
			EVENTS.put(e.getKey() + "." + c, ev);
		}
	}

	public static boolean enabled() {
		Boolean on = enabled;
		if (on == null) enabled = on = readFlag();
		return on;
	}

	/** Self-test hook: force the switch (null = read the config again). */
	public static void setEnabledForTest(Boolean on) {
		enabled = on;
	}

	private static boolean readFlag() {
		String sys = System.getProperty("elsewhere.overhaul3." + CONFIG_KEY);
		if (sys != null) return !"false".equalsIgnoreCase(sys.trim());
		try {
			Path p = net.fabricmc.loader.api.FabricLoader.getInstance().getConfigDir().resolve("elsewhere-overhaul3.json");
			if (Files.isRegularFile(p)) {
				com.google.gson.JsonObject o = com.google.gson.JsonParser.parseString(Files.readString(p, StandardCharsets.UTF_8)).getAsJsonObject();
				if (o.has(CONFIG_KEY)) return o.get(CONFIG_KEY).getAsBoolean();
			}
		} catch (Exception ignored) {
			// missing or malformed config keeps the default (on)
		}
		return true;
	}

	public static boolean has(String boss, String cue) {
		return EVENTS.containsKey(boss + "." + cue);
	}

	public static SoundEvent get(String boss, String cue) {
		return EVENTS.get(boss + "." + cue);
	}

	/** The sfx3 event when the switch is on and the cue exists, else {@code fallback}. */
	public static SoundEvent pick(String boss, String cue, SoundEvent fallback) {
		if (!enabled()) return fallback;
		SoundEvent e = get(boss, cue);
		return e == null ? fallback : e;
	}

	private static boolean gate(Entity at, int slot, int gap) {
		long now = at.level().getGameTime();
		long[] last = LAST.computeIfAbsent(at, k -> new long[] {Long.MIN_VALUE / 4, Long.MIN_VALUE / 4, Long.MIN_VALUE / 4});
		if (now - last[slot] < gap) return false;
		last[slot] = now;
		return true;
	}

	private static void emit(ServerLevel level, Entity at, SoundEvent e, float volume, float pitch) {
		if (e != null) level.playSound(null, at.getX(), at.getY(), at.getZ(), e, SoundSource.HOSTILE, volume, pitch);
	}

	/** Phase-change roar: signature plus its vanilla layer. False when off or this boss has none (caller plays its old sound). */
	public static boolean roar(Entity at, String boss) {
		if (!enabled() || !has(boss, "roar") || !(at.level() instanceof ServerLevel level)) return false;
		if (gate(at, 0, 40)) {
			emit(level, at, get(boss, "roar"), 3.0F, 1.0F);
			emit(level, at, get(boss, "roar_layer"), 2.0F, 1.0F);
		}
		return true;
	}

	/** Attack tell: the boss's telegraph motif at a fixed pitch per attack id, so players learn each attack by ear. */
	public static boolean tele(Entity at, String boss, String attackId, boolean big) {
		if (!enabled() || !has(boss, "tele") || !(at.level() instanceof ServerLevel level)) return false;
		if (gate(at, 1, 10)) {
			emit(level, at, get(boss, "tele"), big ? 2.2F : 1.5F, attackPitch(attackId) * (big ? 0.9F : 1.0F));
			if (big) emit(level, at, get(boss, "big"), 2.0F, 1.0F);
		}
		return true;
	}

	/** Replaces Openings.windupTell's shared ravager roar with this boss's tell; keeps its sparks. */
	public static boolean windup(ServerLevel level, LivingEntity boss, String bossId, String attackId, boolean big) {
		if (!tele(boss, bossId, attackId, big)) return false;
		level.sendParticles(ParticleTypes.ANGRY_VILLAGER, boss.getX(), boss.getY() + boss.getBbHeight() + 0.3, boss.getZ(), big ? 6 : 2, 0.5, 0.2, 0.5, 0.0);
		return true;
	}

	/** Death: its own death file, else the roar slowed down, plus the vanilla layer. */
	public static boolean death(Entity at, String boss) {
		if (!enabled() || !(has(boss, "death") || has(boss, "roar")) || !(at.level() instanceof ServerLevel level)) return false;
		if (gate(at, 2, 40)) {
			boolean own = has(boss, "death");
			emit(level, at, get(boss, own ? "death" : "roar"), 3.0F, own ? 1.0F : 0.7F);
			emit(level, at, get(boss, "roar_layer"), 2.0F, 0.7F);
		}
		return true;
	}

	/** Fixed pitch per attack id, five steps from 0.84 to 1.16. */
	public static float attackPitch(String attackId) {
		return 0.84F + 0.08F * Math.floorMod(attackId == null ? 0 : attackId.hashCode(), 5);
	}

	public static List<String> paths() {
		List<String> out = new ArrayList<>();
		for (var e : CUES.entrySet()) for (String c : e.getValue()) out.add("sfx3." + e.getKey() + "." + c);
		return Collections.unmodifiableList(out);
	}

	/**
	 * Self-test: every sfx3 event is registered, is in sounds.json with a subtitle that en_us.json has, every file it
	 * names is in the jar, every vanilla event it names is registered, and nothing it plays is an ender dragon or wither
	 * sound. Returns the problems (empty = pass).
	 */
	public static List<String> selfCheck() {
		List<String> bad = new ArrayList<>();
		com.google.gson.JsonObject sounds = readJson("/assets/elsewhere/sounds.json", bad);
		com.google.gson.JsonObject lang = readJson("/assets/elsewhere/lang/en_us.json", bad);
		if (sounds == null || lang == null) return bad;
		for (String path : paths()) {
			if (!BuiltInRegistries.SOUND_EVENT.containsKey(Identifier.fromNamespaceAndPath("elsewhere", path))) bad.add(path + ": not registered");
			if (!sounds.has(path)) { bad.add(path + ": not in sounds.json"); continue; }
			com.google.gson.JsonObject def = sounds.getAsJsonObject(path);
			String sub = def.has("subtitle") ? def.get("subtitle").getAsString() : null;
			if (sub == null || !lang.has(sub)) bad.add(path + ": subtitle missing (" + sub + ")");
			checkSounds(path, def, sounds, bad, 0);
		}
		return bad;
	}

	private static void checkSounds(String path, com.google.gson.JsonObject def, com.google.gson.JsonObject sounds, List<String> bad, int depth) {
		if (!def.has("sounds") || def.getAsJsonArray("sounds").isEmpty()) { bad.add(path + ": no sounds"); return; }
		for (var el : def.getAsJsonArray("sounds")) {
			String name = el.isJsonPrimitive() ? el.getAsString() : el.getAsJsonObject().get("name").getAsString();
			boolean event = el.isJsonObject() && el.getAsJsonObject().has("type") && "event".equals(el.getAsJsonObject().get("type").getAsString());
			if (name.contains("ender_dragon") || name.contains("enderdragon") || name.matches(".*(entity\\.wither\\.(?!skeleton)|mob/wither/).*")) {
				bad.add(path + ": plays a dragon/wither sound " + name);
			}
			Identifier id = Identifier.parse(name);
			if (event) {
				if (!BuiltInRegistries.SOUND_EVENT.containsKey(id)) bad.add(path + ": unknown event " + name);
				else if ("elsewhere".equals(id.getNamespace()) && depth < 3 && sounds.has(id.getPath())) checkSounds(path, sounds.getAsJsonObject(id.getPath()), sounds, bad, depth + 1);
			} else if (!"elsewhere".equals(id.getNamespace())) {
				bad.add(path + ": vanilla file reference " + name + " (use a vanilla event)");
			} else if (Sfx3.class.getResource("/assets/elsewhere/sounds/" + id.getPath() + ".ogg") == null) {
				bad.add(path + ": missing file sounds/" + id.getPath() + ".ogg");
			}
		}
	}

	/**
	 * Every copy of {@code res} on the classpath merged, first copy winning per key, like the game's resource stack and the
	 * merged jar. In a dev run each module and each devlibs jar can bring its own sounds.json or en_us.json, and the first
	 * one found need not be this module's.
	 */
	private static com.google.gson.JsonObject readJson(String res, List<String> bad) {
		com.google.gson.JsonObject out = null;
		try {
			ClassLoader cl = Sfx3.class.getClassLoader();
			java.util.Enumeration<java.net.URL> urls = cl.getResources(res.substring(1));
			while (urls.hasMoreElements()) {
				try (InputStream in = urls.nextElement().openStream()) {
					com.google.gson.JsonObject o = com.google.gson.JsonParser.parseReader(new InputStreamReader(in, StandardCharsets.UTF_8)).getAsJsonObject();
					if (out == null) out = new com.google.gson.JsonObject();
					for (var e : o.entrySet()) if (!out.has(e.getKey())) out.add(e.getKey(), e.getValue());
				}
			}
			if (out == null) {
				try (InputStream in = Sfx3.class.getResourceAsStream(res)) {
					if (in != null) out = com.google.gson.JsonParser.parseReader(new InputStreamReader(in, StandardCharsets.UTF_8)).getAsJsonObject();
				}
			}
		} catch (Exception e) {
			bad.add(res + " unreadable: " + e);
			return null;
		}
		if (out == null) bad.add(res + " missing");
		return out;
	}
}
