/**
 * The 3D head ornaments of Azmar's headpieces (RIVALS-DECISIONS 9.3): cobra and striped nemes, ibis head with plumes, falcon beak and
 * wings, jackal ears and muzzle, horned scarab. Real geometry (cubes of {@code azmar_ornaments.json}, generated by tools/gen_ornaments.py)
 * drawn on the head of every humanoid that wears the matching real headpiece; the equipment (armor) layer stays underneath.
 */
public final class OrnamentLayer<S extends HumanoidRenderState, M extends EntityModel<S> & HeadedModel> extends RenderLayer<S, M> {
	private static final Map<String, String> BY_ITEM = Map.of(
		"azmar_nemes_of_the_uraeus", "nemes", "azmar_ibis_crest", "ibis", "azmar_falcon_helm", "falcon", "azmar_jackal_helm", "jackal", "azmar_horned_scarab_crown", "scarab");
	private static final Map<String, OrnamentModel> MODELS = new HashMap<>();
	/** Baked parts of one ornament model (the falcon uses its own). */
	static ModelPart rootOf(String ornament) {
		load();
		OrnamentModel m = MODELS.get(ornament);
		return m == null ? null : m.root();
	}

	static Identifier atlas() {
		load();
		return texture;
	}
	private static Identifier texture;
	private static boolean loaded;

	@SuppressWarnings("unchecked")
	public OrnamentLayer(RenderLayerParent<S, M> parent) {
		super(parent);
		load();
	}

	/** Which ornament a worn head item gets, or null. */
	public static String ornamentOf(ItemStack head) {
		if (head == null || head.isEmpty()) return null;
		var key = BuiltInRegistries.ITEM.getKey(head.getItem());
		return "elsewhere".equals(key.getNamespace()) ? BY_ITEM.get(key.getPath()) : null;
	}

	static synchronized void load() {
		if (loaded) return;
		loaded = true;
		try (InputStream in = OrnamentLayer.class.getResourceAsStream("/assets/elsewhere/azmar_ornaments.json")) {
			JsonObject root = JsonParser.parseReader(new InputStreamReader(in, StandardCharsets.UTF_8)).getAsJsonObject();
			texture = Identifier.parse(root.get("texture").getAsString());
			int tw = root.get("width").getAsInt(), th = root.get("height").getAsInt();
			for (var e : root.getAsJsonObject("ornaments").entrySet()) {
				MeshDefinition mesh = new MeshDefinition();
				PartDefinition rootPart = mesh.getRoot();
				for (JsonElement ce : e.getValue().getAsJsonArray()) {
					JsonObject c = ce.getAsJsonObject();
					float[] o = f(c.getAsJsonArray("o")), s = f(c.getAsJsonArray("s")), p = f(c.getAsJsonArray("p")), r = f(c.getAsJsonArray("r"));
					JsonArray uv = c.getAsJsonArray("uv");
					rootPart.addOrReplaceChild(c.get("n").getAsString(), CubeListBuilder.create().texOffs(uv.get(0).getAsInt(), uv.get(1).getAsInt()).addBox(o[0], o[1], o[2], s[0], s[1], s[2]),
						PartPose.offsetAndRotation(p[0], p[1], p[2], r[0], r[1], r[2]));
				}
				MODELS.put(e.getKey(), new OrnamentModel(LayerDefinition.create(mesh, tw, th).bakeRoot()));
			}
		} catch (Exception ex) {
			dev.elsewhere.rivals.azmar.AzmarContent.LOG.error("Azmar ornaments failed to load", ex);
		}
	}

	private static float[] f(JsonArray a) {
		float[] r = new float[a.size()];
		for (int i = 0; i < r.length; i++) r[i] = a.get(i).getAsFloat();
		return r;
	}

	@Override
	public void submit(PoseStack pose, SubmitNodeCollector collector, int light, S state, float yRot, float xRot) {
		String id = ornamentOf(state.headEquipment);
		OrnamentModel m = id == null ? null : MODELS.get(id);
		if (m == null || texture == null) return;
		pose.pushPose();
		getParentModel().translateToHead(pose);
		collector.order(1).submitModel(m, state, pose, RenderTypes.entityCutout(texture), light, LivingEntityRenderer.getOverlayCoords(state, 0.0F), -1, null, state.outlineColor);
		pose.popPose();
	}

	/** Static cubes, no animation. */
	static final class OrnamentModel extends Model<Object> {
		OrnamentModel(ModelPart root) {
			super(root, RenderTypes::entityCutout);
		}
	}
}
