"""Box-model generator shared by every boss: one spec -> Java LayerDefinition (exact UVs) + painted texture.

A spec is a list of parts: Part(name, parent, pivot, rot_deg, cubes). Each cube is Cube(x, y, z, w, h, d, material,
inflate=0, faces=None, share=None). The generator packs every cube's box-UV net into the atlas, emits Java that uses
those texOffs, and paints each face with the material's painter (plus optional per-face decorators such as eyes).
Variants (e.g. "charged") repaint the same layout with material overrides into a second PNG.
"""
import math, os, random
from PIL import Image

class Cube:
    def __init__(self, x, y, z, w, h, d, mat, inflate=0.0, faces=None, share=None, name=None):
        self.x, self.y, self.z, self.w, self.h, self.d = x, y, z, int(w), int(h), int(d)
        self.mat, self.inflate, self.faces, self.share, self.name = mat, inflate, faces or {}, share, name
        self.u = self.v = None

class Part:
    def __init__(self, name, parent, pivot=(0, 0, 0), rot=(0, 0, 0), cubes=()):
        self.name, self.parent, self.pivot, self.rot, self.cubes = name, parent, pivot, rot, list(cubes)

def pack(parts, tw, th):
    cubes = [c for p in parts for c in p.cubes if c.share is None]
    named = {c.name: c for p in parts for c in p.cubes if c.name}
    order = sorted(cubes, key=lambda c: -(c.d + c.h))
    x = y = row_h = 0
    for c in order:
        cw, ch = 2 * (c.d + c.w), c.d + c.h
        if x + cw > tw:
            x, y, row_h = 0, y + row_h, 0
        if y + ch > th:
            raise SystemExit("texture %dx%d too small" % (tw, th))
        c.u, c.v = x, y
        x += cw
        row_h = max(row_h, ch)
    for p in parts:
        for c in p.cubes:
            if c.share is not None:
                src = named[c.share]
                c.u, c.v = src.u, src.v
                assert (src.w, src.h, src.d) == (c.w, c.h, c.d), "shared UV needs equal size"

def face_rects(c):
    u, v, w, h, d = c.u, c.v, c.w, c.h, c.d
    return {
        "up": (u + d, v, w, d), "down": (u + d + w, v, w, d),
        "east": (u, v + d, d, h), "north": (u + d, v + d, w, h),
        "west": (u + d + w, v + d, d, h), "south": (u + d + w + d, v + d, w, h),
    }

def paint(parts, tw, th, materials, decorators, seed=1):
    img = Image.new("RGBA", (tw, th), (0, 0, 0, 0))
    rng = random.Random(seed)
    for p in parts:
        for c in p.cubes:
            if c.share is not None:
                continue
            for face, (fx, fy, fw, fh) in face_rects(c).items():
                if fw <= 0 or fh <= 0:
                    continue
                tile = Image.new("RGBA", (fw, fh))
                materials[c.mat](tile, face, rng)
                deco = c.faces.get(face)
                if deco:
                    for dname in deco.split("+"):
                        decorators[dname](tile, face, rng)
                img.paste(tile, (fx, fy))
    return img

def fmt(v):
    s = ("%.3f" % v).rstrip("0").rstrip(".")
    if s in ("-0", ""):
        s = "0"
    return s + "F"

def java(pkg, cls, parts, tw, th, doc):
    lines = ["package %s;" % pkg, "",
             "import net.minecraft.client.model.geom.PartPose;",
             "import net.minecraft.client.model.geom.builders.CubeDeformation;",
             "import net.minecraft.client.model.geom.builders.CubeListBuilder;",
             "import net.minecraft.client.model.geom.builders.LayerDefinition;",
             "import net.minecraft.client.model.geom.builders.MeshDefinition;",
             "import net.minecraft.client.model.geom.builders.PartDefinition;", "",
             "/** GENERATED by tools/gen_models.py, do not edit. %s */" % doc,
             "public final class %s {" % cls,
             "\tprivate %s() {}" % cls, "",
             "\tpublic static LayerDefinition create() {",
             "\t\tMeshDefinition mesh = new MeshDefinition();",
             "\t\tPartDefinition root = mesh.getRoot();"]
    for p in parts:
        cl = "CubeListBuilder.create()"
        for c in p.cubes:
            cl += ".texOffs(%d, %d).addBox(%s, %s, %s, %d, %d, %d%s)" % (
                c.u, c.v, fmt(c.x), fmt(c.y), fmt(c.z), c.w, c.h, c.d,
                (", new CubeDeformation(%s)" % fmt(c.inflate)) if c.inflate else "")
        rx, ry, rz = (math.radians(a) for a in p.rot)
        pose = "PartPose.offsetAndRotation(%s, %s, %s, %s, %s, %s)" % (fmt(p.pivot[0]), fmt(p.pivot[1]), fmt(p.pivot[2]), fmt(rx), fmt(ry), fmt(rz))
        var = "p_" + p.name
        lines.append("\t\tPartDefinition %s = %s.addOrReplaceChild(\"%s\", %s, %s);" % (
            var, "root" if p.parent == "root" else "p_" + p.parent, p.name, cl, pose))
    lines += ["\t\treturn LayerDefinition.create(mesh, %d, %d);" % (tw, th), "\t}", "}", ""]
    return "\n".join(lines)

# ---------------------------------------------------------------------------------------- painters

def hexc(s, a=255):
    s = s.lstrip("#")
    return (int(s[0:2], 16), int(s[2:4], 16), int(s[4:6], 16), a)

def mix(a, b, t):
    return tuple(int(a[i] + (b[i] - a[i]) * t) for i in range(4))

def noise_mat(colors, weights=None, vgrad=None, border=None, alpha=255):
    """Random pixel noise from a palette; optional vertical gradient (top color, bottom color, strength) and darker border."""
    cols = [hexc(c, alpha) for c in colors]
    def painter(tile, face, rng):
        w, h = tile.size
        px = tile.load()
        for y in range(h):
            for x in range(w):
                c = rng.choices(cols, weights=weights)[0]
                if vgrad:
                    t = y / max(1, h - 1)
                    c = mix(c, hexc(vgrad[1] if t > 0.5 else vgrad[0]), abs(t - 0.5) * 2 * vgrad[2])
                if border and (x == 0 or y == 0 or x == w - 1 or y == h - 1):
                    c = mix(c, hexc(border), 0.55)
                px[x, y] = c
    return painter

def stripes_mat(c1, c2, period=3, horizontal=True, jitter=None):
    a, b = hexc(c1), hexc(c2)
    j = [hexc(c) for c in (jitter or [])]
    def painter(tile, face, rng):
        w, h = tile.size
        px = tile.load()
        for y in range(h):
            for x in range(w):
                k = (y if horizontal else x) // period
                c = a if k % 2 == 0 else b
                if j and rng.random() < 0.25:
                    c = rng.choice(j)
                px[x, y] = c
    return painter

def rect(tile, x0, y0, x1, y1, col):
    px = tile.load()
    w, h = tile.size
    for y in range(max(0, y0), min(h, y1)):
        for x in range(max(0, x0), min(w, x1)):
            px[x, y] = col

def save(img, path, scale_preview=None):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    img.save(path)
