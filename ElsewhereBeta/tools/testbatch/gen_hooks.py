"""Stage the test-batch injection for a merged ElsewhereBeta tree (s-testbatch, 3.0.0).

argv: <merged tree (holds src/)> <staging dir>
Writes into <staging>/src/main/...: the TestBatch sources and mixins, a generated TestBatchHooks.java (one case per
module self-test, copied verbatim from the merged BetaInit.java, plus the core and nether_end_bosses hooks that live in
their own content init), and patched copies of BetaHooks.java (calls TestBatch.init()) and elsewhere_beta.mixins.json
(the three TestBatch mixins). tools/testbatch.sh rsyncs the staging dir over its own copy of the tree; the merged tree
and the shipped jar are never touched.
Fails (exit 1) if a module that halts on <id>.selftest.exit has no hook, so a new module can't be skipped silently.
"""
import json, os, re, shutil, sys

tree, stage = sys.argv[1], sys.argv[2]
HERE = os.path.dirname(os.path.abspath(__file__))
J = os.path.join(tree, "src/main/java/dev/elsewhere")
OUTJ = os.path.join(stage, "src/main/java/dev/elsewhere")
read = lambda p: open(p, encoding="utf-8").read()

hooks = {}  # id -> java statement(s)
beta_init = read(os.path.join(J, "beta/BetaInit.java"))
for line in beta_init.splitlines():
    s = line.strip()
    m = re.match(r'if \(Boolean\.getBoolean\("([a-z0-9_]+)\.selftest"\)\) (.*)$', s)
    if m:
        hooks[m.group(1)] = s
        continue
    # unconditional self-test inits that read <id>.selftest themselves (verdigris_ironpeak)
    m = re.match(r'(dev\.elsewhere\.[\w.]+\.SelfTest)\.init\(\);$', s)
    if m:
        src = os.path.join(tree, "src/main/java", m.group(1).replace(".", "/") + ".java")
        ids = re.findall(r'getBoolean\("([a-z0-9_]+)\.selftest"\)', read(src)) if os.path.exists(src) else []
        if ids:
            hooks[ids[0]] = s

# hooks that live in a module's own content init, not in BetaInit
EXTRA = {
    "elsewhere": ("Elsewhere.java", r'if \(Boolean\.getBoolean\("elsewhere\.selftest"\)\) \{\s*SelfTest\.register\(\);\s*\}',
                  "dev.elsewhere.test.SelfTest.register();"),
    "nether_end_bosses": ("nether_end_bosses/NetherEndBossesContent.java",
                          r'if \(Boolean\.getBoolean\("nether_end_bosses\.selftest"\)\) \{\s*ServerLifecycleEvents\.SERVER_STARTED\.register\(SelfTest::start\);\s*ServerTickEvents\.END_SERVER_TICK\.register\(SelfTest::tick\);\s*\}',
                          "dev.elsewhere.nether_end_bosses.TestBatchNebHook.register();"),  # SelfTest.start/tick are package-private
}
bad = []
for mid, (rel, pat, stmt) in EXTRA.items():
    p = os.path.join(J, rel)
    if not os.path.exists(p) or not re.search(pat, read(p)):
        bad.append(f"{mid}: its self-test hook in {rel} changed; update EXTRA in tools/testbatch/gen_hooks.py")
    else:
        hooks[mid] = stmt

# every module whose test halts on <id>.selftest.exit must have a hook
exits = set()
for root, _, files in os.walk(J):
    for f in files:
        if f.endswith(".java"):
            exits.update(re.findall(r'getBoolean\("([a-z0-9_.]+)\.selftest\.exit"\)', read(os.path.join(root, f))))
exits.discard("elsewhere.armies")  # the armies bench runs only when no other self-test runs (ArmiesConfig.otherSelfTest)
exits.discard("elsewhere.townsfolk")  # townsfolk bench: package-private register(), runs standalone (lead 16:20, lane-tf run)
for mid in sorted(exits - set(hooks)):
    bad.append(f"{mid}: halts on {mid}.selftest.exit but no hook was found")
if bad:
    print("gen_hooks: " + "\n gen_hooks: ".join(bad))
    sys.exit(1)

ids = sorted(hooks)
cases = "\n".join(f'\t\t\tcase "{i}" -> {{\n\t\t\t\t{hooks[i]}\n\t\t\t}}' for i in ids)
java = f'''package dev.elsewhere.beta.testbatch;

/** GENERATED by tools/testbatch/gen_hooks.py from BetaInit.java (+ the core and nether_end_bosses hooks). Do not edit. */
final class TestBatchHooks {{
	private TestBatchHooks() {{}}

	static final String[] IDS = {{{", ".join('"%s"' % i for i in ids)}}};

	static boolean has(String id) {{
		for (String s : IDS) if (s.equals(id)) return true;
		return false;
	}}

	static void register(String id) {{
		switch (id) {{
{cases}
			default -> throw new IllegalArgumentException("no self-test hook for " + id);
		}}
	}}
}}
'''
if os.path.isdir(stage):
    shutil.rmtree(stage)
os.makedirs(os.path.join(OUTJ, "beta/testbatch"))
os.makedirs(os.path.join(OUTJ, "beta/mixin"))
open(os.path.join(OUTJ, "beta/testbatch/TestBatchHooks.java"), "w").write(java)
SRC = os.path.join(HERE, "java/dev/elsewhere/beta")
for sub in ("testbatch", "mixin"):
    for f in os.listdir(os.path.join(SRC, sub)):
        shutil.copy(os.path.join(SRC, sub, f), os.path.join(OUTJ, "beta", sub, f))

os.makedirs(os.path.join(OUTJ, "nether_end_bosses"))
open(os.path.join(OUTJ, "nether_end_bosses/TestBatchNebHook.java"), "w").write('''package dev.elsewhere.nether_end_bosses;

/** Test batch only (generated by tools/testbatch/gen_hooks.py): NetherEndBossesContent's self-test hook (SelfTest.start/tick are package-private). */
public final class TestBatchNebHook {
	private TestBatchNebHook() {}

	public static void register() {
		net.fabricmc.fabric.api.event.lifecycle.v1.ServerLifecycleEvents.SERVER_STARTED.register(SelfTest::start);
		net.fabricmc.fabric.api.event.lifecycle.v1.ServerTickEvents.END_SERVER_TICK.register(SelfTest::tick);
	}
}
''')

hb = read(os.path.join(J, "beta/BetaHooks.java"))
anchor = "public static void afterModules() {"
assert anchor in hb, "BetaHooks.afterModules() not found"
hb = hb.replace(anchor, anchor + "\n\t\tdev.elsewhere.beta.testbatch.TestBatch.init();", 1)
open(os.path.join(OUTJ, "beta/BetaHooks.java"), "w").write(hb)

mj_path = os.path.join(tree, "src/main/resources/elsewhere_beta.mixins.json")
mj = json.load(open(mj_path))
for n in ("TestBatchEventMixin", "TestBatchServerMixin", "TestBatchLevelMixin"):
    if n not in mj["mixins"]:
        mj["mixins"].append(n)
os.makedirs(os.path.join(stage, "src/main/resources"))
json.dump(mj, open(os.path.join(stage, "src/main/resources/elsewhere_beta.mixins.json"), "w"), indent=2)
print("gen_hooks: %d module hooks: %s" % (len(ids), ",".join(ids)))
